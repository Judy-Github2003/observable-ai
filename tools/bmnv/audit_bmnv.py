#!/usr/bin/env python3
"""Independent-of-examiner-scoring Python audit over frozen JSONL.
Checks structural integrity, sensor truth table, recomputes predictions and grade metrics.
"""
import argparse, collections, hashlib, json
from pathlib import Path

ARMS=('FULL','NO_MEMORY','NO_OBSERVATION','NO_COMPOSE')
WRAPPERS=('DIRECT','XOR_CONTEXT','AND_CONTEXT','OR_CONTEXT')

def load(path):return [json.loads(s) for s in path.read_text(encoding='utf-8').splitlines() if s.strip()]

def evaluate(expr,r):
    op,first,second=expr.split('|')
    a=r[first.lower()]
    if second == '-':return a if op=='ID' else not a
    b=r[second.lower()]
    return {'XOR':a!=b,'XNOR':a==b,'AND':a and b,'OR':a or b,
        'NAND':not (a and b),'NOR':not(a or b)}[op]

def wrap(mode,z,c):return {'DIRECT':z,'XOR_CONTEXT':z!=c,'AND_CONTEXT':z and c,
                              'OR_CONTEXT':z or c}[mode]

def main():
    p=argparse.ArgumentParser();p.add_argument('--result',required=True);arg=p.parse_args();d=Path(arg.result)
    studentsPath=d/'STUDENTS-FROZEN.jsonl';graderPath=d/'EXAMINER-AFTER-FREEZE.jsonl'
    students=load(studentsPath);grades=load(graderPath)
    actualsha=hashlib.sha256(studentsPath.read_bytes()).hexdigest()
    if (d/'STUDENTS-FROZEN.sha256').read_text().split()[0] != actualsha:
        raise SystemExit('AUDIT_FAIL: students freeze hash mismatch')
    if len(students)!=192 or len(grades)!=192:raise SystemExit('AUDIT_FAIL: expected 192 records each')
    ss={(r['taskId'],r['arm']):r for r in students}; gg={(r['taskId'],r['arm']):r for r in grades}
    if len(ss)!=192 or len(gg)!=192 or ss.keys()!=gg.keys():raise SystemExit('AUDIT_FAIL: duplicated/missing task-arm records')
    tasks=set(k[0] for k in ss)
    if len(tasks)!=48 or any({x[1] for x in ss if x[0]==t}!=set(ARMS) for t in tasks):
        raise SystemExit('AUDIT_FAIL: incomplete paired tasks')
    score=collections.defaultdict(lambda:[0,0,0,0])
    for key,student in ss.items():
        grade=gg[key]
        if student.get('teacherCalls')!=0:raise SystemExit('AUDIT_FAIL: teacher calls nonzero')
        truth=grade['truths'];inputs=grade['heldoutInputs'];pred=student['predictions']
        if len(pred)!=4 or len(truth)!=4 or len(inputs)!=16 or any(len(a)!=16 for a in pred+truth):
            raise SystemExit('AUDIT_FAIL: dimension mismatch')
        for wi,wrapper in enumerate(WRAPPERS):
            recompute=[wrap(wrapper,evaluate(grade['groundTruthExpr'],x),x['context']) for x in inputs]
            if recompute!=truth[wi]:raise SystemExit('AUDIT_FAIL: ground truth wrong')
        accurate=sum(p==t for pp,tt in zip(pred,truth) for p,t in zip(pp,tt) if p is not None)
        covered=sum(p is not None for pp in pred for p in pp)
        models=student['bModelCodes']
        if len(models)!=4 or len(student['bCandidateCounts'])!=4:
            raise SystemExit('AUDIT_FAIL: invalid model ledger')
        for wi, encoded in enumerate(models):
            if encoded is None:
                if any(p is not None for p in pred[wi]):
                    raise SystemExit('AUDIT_FAIL: prediction without model')
            else:
                exprcode, wrapcode = encoded.split('@',1)
                if wrapcode not in WRAPPERS + ('NOT','XNOR_CONTEXT'):
                    raise SystemExit('AUDIT_FAIL: unknown wrapper')
                for j,inp in enumerate(inputs):
                    z=evaluate(exprcode,inp)
                    w=wrapcode
                    expected={'DIRECT':z,'NOT':not z,'AND_CONTEXT':z and inp['context'],
                        'OR_CONTEXT':z or inp['context'],'XOR_CONTEXT':z!=inp['context'],
                        'XNOR_CONTEXT':z==inp['context']}[w]
                    if pred[wi][j] != expected:
                        raise SystemExit('AUDIT_FAIL: prediction not generated by declared model')
        if grade['correct']!=accurate or grade['covered']!=covered or grade['total']!=64:
            raise SystemExit('AUDIT_FAIL: grade arithmetic invalid')
        billed=student['aReads']+sum(student['bTrainReads'])+sum(student['bTestReads'])
        if student['totalReads']!=billed or grade['totalReads']!=billed:raise SystemExit('AUDIT_FAIL: read accounting')
        model=student['aExpr']
        aCorrect=(model is not None and all(evaluate(model,{'alpha':bool(n&1),'beta':bool(n&2),'gamma':bool(n&4)})==
            evaluate(grade['groundTruthExpr'],{'alpha':bool(n&1),'beta':bool(n&2),'gamma':bool(n&4)}) for n in range(8)))
        if aCorrect!=grade['aCorrect']:raise SystemExit('AUDIT_FAIL: A concept scoring')
        if key[1]=='FULL' and student['memory']:
            parts=student['memory'].split('#')
            if len(parts)!=5 or parts[1]!=model:raise SystemExit('AUDIT_FAIL: memory mismatch')
            memPath=d/'PERSISTED-CONCEPTS'/f"{key[0]}.concept"
            if not memPath.is_file() or memPath.read_text(encoding='utf-8')!=student['memory']:
                raise SystemExit('AUDIT_FAIL: disk memory missing/mismatched')
        if key[1]=='FULL' and student['aStatus']=='LEARNED_BOUNDED' and not student['aChannels']:
            raise SystemExit('AUDIT_FAIL: missing A measurement trail')
        row=score[key[1]];row[0]+=accurate;row[1]+=covered;row[2]+=billed;row[3]+=int(aCorrect)
    paired={'fullBetterThanNoMemory':0,'fullWorseThanNoMemory':0,'tied':0}
    for t in tasks:
        a=gg[(t,'FULL')]['correct'];b=gg[(t,'NO_MEMORY')]['correct']
        paired['fullBetterThanNoMemory' if a>b else 'fullWorseThanNoMemory' if a<b else 'tied']+=1
    result={'audit':'PASS_STRUCTURAL', 'scope':'visible-examiner development evaluation; NOT independent closed-book',
        'studentSha256':actualsha,'scenarios':48,'studentRecords':len(students),
        'armSummary':{k:{'correct':v[0],'coverage':v[1],'outOf':3072,'reads':v[2],'aConceptCorrectCount':v[3]} for k,v in sorted(score.items())},
        'pairedFullVsNoMemory':paired,
        'caution':'Semantically audited published rows; cannot prove one-shot execution or absence of answer leakage from logs alone.'}
    (d/'AUDIT.json').write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    print('BMNV01_AUDIT_PASS_STRUCTURAL',json.dumps(result['armSummary']))

if __name__=='__main__':main()
